// Named placeholders keep word order translatable: t('读到 {n} 项', { n: 3 }).
export function t(zh, vars) {
  let text = LANG === 'en' ? (EN[zh] ?? zh) : zh;
  if (vars) text = text.replace(/\{(\w+)\}/g, (whole, key) => (key in vars ? String(vars[key]) : whole));
  return text;
}

const ATTRS = ['aria-label', 'title', 'placeholder'];
// Static markup carries no translation keys: match on the Chinese source text instead, so the HTML
// needs no data-i18n plumbing and stays readable in its original language.
export function translateDom(root = globalThis.document) {
  if (!root || LANG !== 'en') { if (root?.documentElement) root.documentElement.lang = 'zh-CN'; return; }
  if (root.documentElement) root.documentElement.lang = 'en';
  const walker = root.createTreeWalker(root.body || root, NodeFilter.SHOW_TEXT);
  const pending = [];
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    // Endonyms stay in their own language: the picker must read 中文 / English whichever way it is set.
    if (node.parentElement?.closest('[data-i18n-skip]')) continue;
    const raw = node.nodeValue, key = raw.trim();
    if (key && EN[key]) pending.push([node, raw.replace(key, EN[key])]);
  }
  for (const [node, value] of pending) node.nodeValue = value;
  for (const el of (root.body || root).querySelectorAll('[' + ATTRS.join('],[') + ']')) {
    if (el.closest('[data-i18n-skip]')) continue;
    for (const attr of ATTRS) {
      const value = el.getAttribute(attr);
      if (value && EN[value.trim()]) el.setAttribute(attr, EN[value.trim()]);
    }
  }
}
